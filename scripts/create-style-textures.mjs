import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Independent deterministic SVG textures: no downloaded site artwork.
let seed = 20261120;
function random() {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  return seed / 4294967296;
}
function svg(width, height, content) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" shape-rendering="crispEdges">${content}</svg>`;
}
function url(image) {
  return `url("data:image/svg+xml,${encodeURIComponent(image)}")`;
}

const grain = Array.from({ length: 380 }, () => {
  const x = Math.floor(random() * 128);
  const y = Math.floor(random() * 128);
  const color = random() > .25 ? '#8a7250' : '#fff9e9';
  const opacity = (.05 + random() * .12).toFixed(2);
  return `<rect x="${x}" y="${y}" width="${random() > .8 ? 2 : 1}" height="1" fill="${color}" opacity="${opacity}"/>`;
}).join('');

const wood = Array.from({ length: 110 }, () => {
  const x = Math.floor(random() * 256);
  const y = Math.floor(random() * 128);
  const width = 12 + Math.floor(random() * 100);
  return `<rect x="${x}" y="${y}" width="${width}" height="${1 + Math.floor(random() * 2)}" fill="${random() > .5 ? '#2b2118' : '#97704a'}" opacity="${(.08 + random() * .2).toFixed(2)}"/>`;
}).join('');

const waves = Array.from({ length: 40 }, () => {
  const x = Math.floor(random() * 128);
  const y = Math.floor(random() * 96);
  return `<path d="M${x} ${y}h2v1h3v-1h2" fill="none" stroke="#486874" stroke-opacity=".28" stroke-width=".5"/>`;
}).join('');

const output = fileURLToPath(new URL('../docs/style-guide/assets/', import.meta.url));
await mkdir(output, { recursive: true });
const css = `/* Generated by scripts/create-style-textures.mjs; deterministic and editable. */\n:root {\n  --paper-texture: ${url(svg(128, 128, grain))};\n  --wood-texture: ${url(svg(256, 128, wood))};\n  --wave-texture: ${url(svg(128, 96, waves))};\n}\n`;
await writeFile(new URL('../docs/style-guide/assets/textures.css', import.meta.url), css);
console.log('Created independent paper, wood, and wave texture samples.');
